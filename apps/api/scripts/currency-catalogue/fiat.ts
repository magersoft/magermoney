/**
 * Scales that are decided here rather than read from ICU.
 *
 * ICU carries CLDR's *display* rounding, which is not always ISO's minor unit:
 * CLDR prints a rupiah with no decimals because nobody quotes sen any more, and
 * the two runtimes in this repo ship different CLDR vintages, so deriving the
 * scale gives a different answer under Bun and under Node. For the nine fiats
 * the first catalogue shipped that is not a judgement call at all — accounts
 * already hold balances at these scales, and changing one would reinterpret
 * stored money.
 */
export const SHIPPED_FIAT_SCALE: Readonly<Record<string, number>> = {
  USD: 2,
  EUR: 2,
  RUB: 2,
  KZT: 2,
  UZS: 2,
  IDR: 2,
  EGP: 2,
  GEL: 2,
  KGS: 2,
};

